def for_campus(campus: str | None) -> list[str]:
    """그 캠퍼스 학과 이름 (캠퍼스를 모르면 전부). 되묻기 선택지로 쓴다."""
    return [n for n, (c, _) in DEPARTMENTS.items() if not campus or c in (campus, "공통")]


def keywords(dept: str | None) -> tuple[str, ...]:
    return DEPARTMENTS.get(dept or "", ("", ()))[1]


def find_in(question: str) -> str | None:
    """질문에 학과 이름이 있으면 그 학과 ('간호학과 공모전' → '간호학과', 'AI소프트웨어' → 'AI소프트웨어학과')."""
    compact = question.replace(" ", "")
    for name in DEPARTMENTS:
        stem = name.removesuffix("학과").removesuffix("학부").removesuffix("과")
        if name in compact or (len(stem) >= 2 and stem in compact):
            return name
    return None
